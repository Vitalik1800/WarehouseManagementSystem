"""Безпечні українські повідомлення про помилки для GUI."""

from frontend.app.api.client import APIClientError, APIConnectionError, APIRequestError

_HTTP_MESSAGES = {
    400: "Некоректний запит. Перевірте введені дані.",
    401: "Сеанс авторизації недійсний або завершився. Увійдіть повторно.",
    403: "Недостатньо прав для виконання цієї операції.",
    404: "Запис або ресурс не знайдено.",
    409: "Конфлікт даних. Запис уже існує або використовується.",
    422: "Дані не пройшли перевірку. Перевірте заповнені поля.",
    429: "Забагато запитів. Спробуйте пізніше.",
    500: "Внутрішня помилка сервера. Спробуйте пізніше.",
    502: "Сервер тимчасово недоступний. Спробуйте пізніше.",
    503: "Сервіс тимчасово недоступний. Спробуйте пізніше.",
    504: "Сервер не відповів вчасно. Спробуйте пізніше.",
}


def format_gui_error(error: Exception) -> str:
    """Повертає повідомлення без технічних деталей і даних відповіді сервера."""
    if isinstance(error, APIConnectionError):
        return "Немає зв'язку із сервером. Перевірте підключення та спробуйте знову."
    if isinstance(error, APIRequestError):
        status = error.status_code
        if status in _HTTP_MESSAGES:
            return _HTTP_MESSAGES[status]
        if 500 <= status <= 599:
            return "Помилка сервера. Спробуйте пізніше."
        return "Не вдалося виконати запит. Перевірте дані та спробуйте знову."
    if isinstance(error, APIClientError):
        return "Помилка обміну даними із сервером. Спробуйте знову."
    if isinstance(error, ValueError):
        return "Некоректні дані. Перевірте введені значення."
    return "Не вдалося виконати операцію. Спробуйте знову."
